def writer_user_prompt(
    *,
    product_name: str,
    category: str,
    rating: int,
    pros: list[str],
    cons: list[str],
    purchase_reason: str,
    personal_note: str,
    tone: str,
    length: str,
    review_format: str,
    variant_count: int,
) -> str:
    lines = [
        f"제품: {product_name} ({category})",
        f"구매자가 매긴 별점: {rating}점 / 5점",
        "",
        "구매자가 고른 만족한 점:",
    ]
    if pros:
        lines.extend(f"- {p}" for p in pros)
    else:
        lines.append("- (없음)")

    lines.append("")
    lines.append("구매자가 고른 아쉬운 점:")
    if cons:
        lines.extend(f"- {c}" for c in cons)
    else:
        lines.append("- (없음)")

    if purchase_reason.strip():
        lines.append("")
        lines.append("구매자가 밝힌 구매 이유:")
        lines.append(purchase_reason.strip())

    if personal_note.strip():
        lines.append("")
        lines.append("구매자가 직접 덧붙인 실제 경험 (최우선 반영):")
        lines.append(personal_note.strip())

    lines.extend(
        [
            "",
            "형식:",
            FORMAT_GUIDE.get(review_format, review_format),
            "",
            f"톤: {TONE_GUIDE.get(tone, tone)}",
            f"분량: {LENGTH_GUIDE.get(length, length)}",
            "",
            f"위 조건으로 서로 다른 리뷰 {variant_count}편을 써주세요.",
            "각 편은 소재를 꺼내는 순서와 시작 문장이 서로 달라야 합니다.",
            "",
            "title 에는 리뷰 목록에 노출될 한 줄 제목을 15~30자로 적으세요.",
            "  제품명을 그대로 옮기지 말고, 이 리뷰의 결론이 드러나게 씁니다.",
            "style_label 에는 그 편의 성격을 4~10자로 적으세요.",
            "keywords 에는 실제로 리뷰 본문에 반영된 키워드만 넣으세요.",
            "",
            "분량 지시는 반드시 지키세요. 지정된 글자 수의 70% 미만이면 실패입니다.",
        ]
    )
    return "\n".join(lines)
